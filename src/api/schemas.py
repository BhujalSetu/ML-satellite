# ─────────────────────────────────────────────────────────────────────────────
# 3. POST /api/v1/satellite/analyze
# ─────────────────────────────────────────────────────────────────────────────
class SatelliteAnalyzeRequest(BaseModel):
    """Request contract for single-observation satellite analysis."""
    latitude: float = Field(..., ge=-90.0, le=90.0, description="Center latitude of AOI (-90 to 90)")
    longitude: float = Field(..., ge=-180.0, le=180.0, description="Center longitude of AOI (-180 to 180)")
    buffer: Optional[float] = Field(default=0.05, gt=0.0, le=5.0, description="Half-width buffer in degrees")
    start_date: Optional[date] = Field(default=None, description="Start date for scene query (YYYY-MM-DD)")
    end_date: Optional[date] = Field(default=None, description="End date for scene query (YYYY-MM-DD)")
    max_cloud: Optional[float] = Field(default=20.0, ge=0.0, le=100.0, description="Maximum allowed cloud cover percentage")

    @model_validator(mode="after")
    def validate_date_range(self):
        if self.start_date and self.end_date and self.start_date > self.end_date:
            raise ValueError(f"Invalid date range: start_date ({self.start_date}) cannot be after end_date ({self.end_date})")
        return self


class SceneMetadataSummary(BaseModel):
    """Metadata summary of the analyzed Sentinel-2 scene."""
    scene_id: str = Field(..., description="Unique Sentinel-2 scene identifier")
    date: str = Field(..., description="Acquisition date (YYYY-MM-DD)")
    cloud_cover: float = Field(..., ge=0.0, le=100.0, description="Cloud cover percentage (0-100)")
    acquisition_datetime: Optional[str] = Field(default=None, description="Full ISO acquisition timestamp")


class RasterIndexStats(BaseModel):
    """Summary statistics for a spectral index raster (NDVI/NDWI)."""
    mean: float = Field(..., description="Mean value across valid cells")
    min: float = Field(..., description="Minimum valid value")
    max: float = Field(..., description="Maximum valid value")
    std: Optional[float] = Field(default=None, description="Standard deviation across valid cells")


class SatelliteIndices(BaseModel):
    """Vegetation and water index statistical summaries."""
    ndvi: RasterIndexStats = Field(..., description="Normalized Difference Vegetation Index statistics")
    ndwi: RasterIndexStats = Field(..., description="Normalized Difference Water Index statistics")


class SatelliteAnalyzeOutputs(BaseModel):
    """API-relative URLs for single-observation raster products."""
    ndvi_raster_url: str = Field(..., description="API-relative URL path to NDVI GeoTIFF (/files/satellite/...)")
    ndwi_raster_url: str = Field(..., description="API-relative URL path to NDWI GeoTIFF (/files/satellite/...)")
    water_mask_url: Optional[str] = Field(default=None, description="API-relative URL path to classified binary water mask GeoTIFF")
    ndvi_url: Optional[str] = Field(default=None, description="Alias for ndvi_raster_url")
    ndwi_url: Optional[str] = Field(default=None, description="Alias for ndwi_raster_url")


class SatelliteAnalyzeResponse(BaseModel):
    """Response contract for satellite biophysical index analysis."""
    success: bool = Field(default=True, description="Indicates whether analysis was successful")
    request_id: str = Field(..., description="Unique request tracking identifier")
    location: Optional[LocationCoordinates] = Field(default=None, description="Observation location coordinates")
    aoi: AOIParameters = Field(..., description="Area of interest parameters")
    scene: SceneMetadataSummary = Field(..., description="Sentinel-2 scene metadata")
    indices: SatelliteIndices = Field(..., description="Computed NDVI and NDWI statistics")
    outputs: SatelliteAnalyzeOutputs = Field(..., description="Generated GeoTIFF product relative URLs")
    processing_time_ms: float = Field(..., ge=0.0, description="Pipeline processing time in milliseconds")


# ─────────────────────────────────────────────────────────────────────────────
# 4. POST /api/v1/satellite/change
# ─────────────────────────────────────────────────────────────────────────────
class SatelliteChangeRequest(BaseModel):
    """Request contract for multi-temporal satellite change detection."""
    latitude: float = Field(..., ge=-90.0, le=90.0, description="Center latitude of AOI (-90 to 90)")
    longitude: float = Field(..., ge=-180.0, le=180.0, description="Center longitude of AOI (-180 to 180)")
    buffer: Optional[float] = Field(default=0.05, gt=0.0, le=5.0, description="Half-width buffer in degrees")
    before_date: Optional[date] = Field(default=None, description="Initial observation date T0 (YYYY-MM-DD)")
    after_date: Optional[date] = Field(default=None, description="Subsequent observation date T1 (YYYY-MM-DD)")

    @model_validator(mode="after")
    def validate_date_order(self):
        if self.before_date is not None and self.after_date is not None:
            if self.before_date >= self.after_date:
                raise ValueError("before_date must be strictly earlier than after_date")
        return self


class SceneObservationItem(BaseModel):
    """Summary of a specific temporal observation."""
    date: str = Field(..., description="Acquisition date (YYYY-MM-DD)")
    scene_id: str = Field(..., description="Sentinel-2 scene product ID")


class NDVIChangePercentages(BaseModel):
    """Vegetation change distribution percentages."""
    gain_percent: float = Field(..., ge=0.0, le=100.0, description="Percentage of valid cells with vegetation gain")
    loss_percent: float = Field(..., ge=0.0, le=100.0, description="Percentage of valid cells with vegetation loss")
    stable_percent: float = Field(..., ge=0.0, le=100.0, description="Percentage of valid cells with stable vegetation")


class NDWIChangePercentages(BaseModel):
    """Surface water dynamic category percentages."""
    water_gain_percent: float = Field(..., ge=0.0, le=100.0, description="Percentage of cells with water gain / inundation")
    water_loss_percent: float = Field(..., ge=0.0, le=100.0, description="Percentage of cells with water loss / drying")
    stable_percent: float = Field(..., ge=0.0, le=100.0, description="Percentage of cells with stable water or persistent land")


class SatelliteChangeOutputs(BaseModel):
    """API-relative URLs for temporal change GeoTIFF products."""
    ndvi_change_raster_url: Optional[str] = Field(default=None, description="Relative URL to NDVI difference GeoTIFF")
    ndwi_change_raster_url: Optional[str] = Field(default=None, description="Relative URL to NDWI difference GeoTIFF")
    water_change_raster_url: Optional[str] = Field(default=None, description="Relative URL to classified water dynamics GeoTIFF")
    ndvi_classified_raster_url: Optional[str] = Field(default=None, description="Relative URL to classified NDVI dynamics GeoTIFF")
    ndwi_classified_raster_url: Optional[str] = Field(default=None, description="Relative URL to classified NDWI dynamics GeoTIFF")
    summary_json_url: Optional[str] = Field(default=None, description="Relative URL to change statistics JSON")


class SatelliteChangeResponse(BaseModel):
    """Response contract for multi-temporal satellite change detection."""
    success: bool = Field(default=True, description="Indicates whether the request was evaluated")
    request_id: str = Field(..., description="Unique request tracking identifier")
    status: Literal["completed", "unavailable", "pending"] = Field(
        default="completed",
        description="Processing status: 'completed' when two observations exist, 'unavailable' when second scene missing",
    )
    location: Optional[LocationCoordinates] = Field(default=None, description="Observation location coordinates")
    aoi: AOIParameters = Field(..., description="Target Area of Interest parameters")
    before: Optional[SceneObservationItem] = Field(default=None, description="Initial observation T0 metadata")
    after: Optional[SceneObservationItem] = Field(default=None, description="Subsequent observation T1 metadata")
    before_scene: Optional[SceneObservationItem] = Field(default=None, description="Initial observation T0 metadata alias")
    after_scene: Optional[SceneObservationItem] = Field(default=None, description="Subsequent observation T1 metadata alias")
    changes: Optional[Dict[str, Any]] = Field(default=None, description="Detailed change statistics and categories")
    ndvi_change: Optional[NDVIChangePercentages] = Field(default=None, description="Vegetation change distribution")
    ndwi_change: Optional[NDWIChangePercentages] = Field(default=None, description="Water dynamics distribution")
    outputs: Optional[SatelliteChangeOutputs] = Field(default=None, description="Generated temporal GeoTIFF relative URLs")
    processing_time_ms: float = Field(default=0.0, ge=0.0, description="Pipeline processing time in milliseconds")
    notice: Optional[str] = Field(default=None, description="Informational notice if second observation is unavailable")
