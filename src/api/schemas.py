"""
WATERSCOPE-AI — API Pydantic Schemas
Defines Pydantic v2 data contracts for AI object detection, AI change detection,
satellite biophysical analysis, satellite temporal change, and system health checks.
Strictly returns API-relative URLs (/files/...) and prevents local absolute path leaks.
"""

from datetime import date
from typing import List, Optional, Literal, Tuple, Dict, Any
from pydantic import BaseModel, Field, field_validator, model_validator


# ─────────────────────────────────────────────────────────────────────────────
# General & Health Schemas
# ─────────────────────────────────────────────────────────────────────────────
class HealthResponse(BaseModel):
    """Health check response contract."""
    status: str = Field(default="healthy", description="API operational health status")
    service: str = Field(default="WATERSCOPE-AI API", description="Service identifier")
    version: str = Field(default="1.0.0", description="API version")


class LocationCoordinates(BaseModel):
    """Geographic point coordinates."""
    latitude: float = Field(..., ge=-90.0, le=90.0, description="Latitude in degrees (-90 to 90)")
    longitude: float = Field(..., ge=-180.0, le=180.0, description="Longitude in degrees (-180 to 180)")


class AOIParameters(BaseModel):
    """Area of Interest definition centered around a point with degree buffer."""
    latitude: float = Field(..., ge=-90.0, le=90.0, description="Center latitude (-90 to 90)")
    longitude: float = Field(..., ge=-180.0, le=180.0, description="Center longitude (-180 to 180)")
    buffer: float = Field(default=0.05, gt=0.0, le=5.0, description="Degree buffer radius (default ~5.5km)")


# ─────────────────────────────────────────────────────────────────────────────
# 1. POST /api/v1/ai/analyze-image
# ─────────────────────────────────────────────────────────────────────────────
class AIAnalyzeImageRequest(BaseModel):
    """Request metadata for image analysis."""
    latitude: float = Field(..., ge=-90.0, le=90.0, description="Observation latitude (-90 to 90)")
    longitude: float = Field(..., ge=-180.0, le=180.0, description="Observation longitude (-180 to 180)")


class AIDetectionItem(BaseModel):
    """Individual object detection item."""
    class_name: str = Field(..., description="Detected class name (e.g. boat, person, car, etc.)")
    confidence: float = Field(..., ge=0.0, le=1.0, description="Detection confidence score (0.0 to 1.0)")
    bbox: List[float] = Field(..., description="Bounding box [x1, y1, x2, y2]")

    @field_validator("bbox")
    @classmethod
    def validate_bbox(cls, v: List[float]) -> List[float]:
        if len(v) != 4:
            raise ValueError(f"Bounding box must contain exactly 4 coordinates [x1, y1, x2, y2], got {len(v)}")
        return v


class AIDetectionSummary(BaseModel):
    """Summary counts of detected items."""
    objects_detected: int = Field(default=0, ge=0, description="Total count of all detected objects")
    ponds_detected: int = Field(default=0, ge=0, description="Total count of water ponds detected")


class AIAnalyzeImageOutputs(BaseModel):
    """API-relative file URLs generated by image analysis."""
    annotated_image_url: Optional[str] = Field(
        default=None,
        description="API-relative URL path to the annotated image with visual bounding boxes (e.g. /files/ai/...)",
    )


class AIAnalyzeImageResponse(BaseModel):
    """Response contract for single image object detection."""
    success: bool = Field(default=True, description="Indicates whether analysis was successful")
    request_id: str = Field(..., description="Unique request tracking identifier")
    image_id: str = Field(..., description="Identifier of the processed image")
    location: LocationCoordinates = Field(..., description="Geographical location of the image")
    model: str = Field(..., description="Model name and weights version used for inference")
    detections: List[AIDetectionItem] = Field(default_factory=list, description="List of detected objects")
    summary: AIDetectionSummary = Field(..., description="Summary counts of detected objects")
    outputs: AIAnalyzeImageOutputs = Field(..., description="Generated relative output URLs")
    processing_time_ms: float = Field(..., ge=0.0, description="Inference pipeline execution latency in milliseconds")


